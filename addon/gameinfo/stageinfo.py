    @staticmethod
    def get_stage_list(gameid: str) -> tuple:
        match (gameid):
            case 'SADXPC':
                return StageInfo.sa1_stages
            case 'SA2BPC':
                return StageInfo.sa2_stages
            case _:
                return []
            
    @staticmethod
    def get_act_list(gameid: str, levelid: str):
        match (gameid):
            case 'SADXPC':
                match (levelid):
                    case 'StationSquare':
                        return StageInfo.stationsquare_acts
                    case 'EggCarrierExterior':
                        return StageInfo.eggcarrierexterior_acts
                    case 'EggCarrierInterior':
                        return StageInfo.eggcarrierinterior_acts
                    case 'MysticRuins':
                        return StageInfo.mysticruins_acts
                    case 'ThePast':
                        return StageInfo.thepast_acts
                    case _:
                        return StageInfo.sa1_acts
            case 'SA2BPC':
                return []
            case _:
                return []